"""团队模块常量：错误码（HTTP状态码前缀 + 两位序号）"""

CODE_TEAM_NOT_FOUND = 40404      # 团队不存在（HTTP 404）
CODE_NOT_TEAM_MEMBER = 40302     # 非团队成员，无权操作（HTTP 403）
CODE_OWNER_NOT_MEMBER = 40007    # 指定的项目负责人不在团队中（HTTP 400）
CODE_PROJECT_NOT_FOUND = 40405   # 项目不存在（HTTP 404）
CODE_NOT_PROJECT_MEMBER = 40303  # 非项目成员，无权操作（HTTP 403）
CODE_PROJECT_KB_NAME_CONFLICT = 40901  # 项目内知识库名已存在（HTTP 409）
CODE_PROJECT_KB_NOT_FOUND = 40406     # 知识库不存在（HTTP 404）
CODE_ACCOUNT_NOT_FOUND = 40407        # 系统账号不存在（HTTP 404）
CODE_MEMBER_EXISTS = 40902            # 成员已存在（团队/项目）（HTTP 409）
CODE_TARGET_NOT_TEAM_MEMBER = 40009   # 目标账号不是团队成员（HTTP 400）
